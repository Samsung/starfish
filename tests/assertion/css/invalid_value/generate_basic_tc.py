def readjson(fileName):
    fp = open(fileName, 'r')
    jsonobject = json.load(fp)
    fp.close()
    return jsonobject


def make_valid_test(name,value,testName):
    result=''
    if value == 'LENGTH':
        TEMPLATE = '''
        function {{testName}}(){
            //length unit test
            for(var j=0; j < length_units.length; j++){
                for(var k=0; k < 100; k++){
                    property_test(targetElement,'{{name}}',k+length_units[j],k+length_units[j],'Length Unit - normal - '+'{{name}}'+' test');
                }
            }
        }
        '''
        result += Environment().from_string(TEMPLATE).render(name=name,value=value,testName=testName)
    elif value == 'PERCENTAGE':
        TEMPLATE = '''
        function {{testName}}(){
            // % test
            for(var k=0; k < 100; k++){
                property_test(targetElement,'{{name}}',k+'%',k+'%','PERCENTAGE - normal - '+'{{name}}'+' % test');
            }
        }
        '''
        result += Environment().from_string(TEMPLATE).render(name=name,value=value,testName=testName)
    elif value == 'INTEGER':
        TEMPLATE = '''
        function {{testName}}(){
            // % test
            for(var k=0; k < 100; k++){
                property_test(targetElement,'{{name}}',k,k,'INTEGER - normal - '+'{{name}}'+' % test');
            }
        }
        '''
        result += Environment().from_string(TEMPLATE).render(name=name,value=value,testName=testName)
    elif value == 'NUMBER':
        TEMPLATE = '''
        function {{testName}}(){
            // % test
            for(var k=0; k < 100; k++){
                property_test(targetElement,'{{name}}',k,k,'NUMBER - normal - '+'{{name}}'+' % test');
            }
        }
        '''
        result += Environment().from_string(TEMPLATE).render(name=name,value=value,testName=testName)
    elif value == 'AUTO':
        TEMPLATE = '''
        function {{testName}}(){
             property_test(targetElement,'{{name}}','auto','auto','Normal Test : {{testName}}');
        }
        '''
        result += Environment().from_string(TEMPLATE).render(name=name,value=value,testName=testName)
    else:
        TEMPLATE = '''
        function {{testName}}(){
            property_test(targetElement,'{{name}}','{{value}}','{{value}}','Normal Test : {{testName}}');
        }
        '''
        result += Environment().from_string(TEMPLATE).render(name=name,value=value,testName=testName)

    return result+'\n'



