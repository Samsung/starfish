# Flattens the vcpkg fontconfig port's installed fonts.conf + conf.d/*.conf
# into a single self-contained XML document, embedded as a C++ string
# constant. fonts.conf's own <dir>/<cachedir> entries already resolve
# entirely through Windows-native tokens (WINDOWSFONTDIR,
# LOCAL_APPDATA_FONTCONFIG_CACHE, etc. -- see fontconfig's fcxml.c), so the
# only path-dependent piece is the <include>conf.d</include> that pulls in
# the per-file match/alias rules (generic family aliasing, hinting,
# antialiasing defaults, ...). Inlining that directory's files in place of
# the <include> lets the whole config load via FcConfigParseAndLoadFromMemory
# with no fontconfig data files shipped or located at runtime at all.

import optparse
import os
import sys
import xml.etree.ElementTree as ET

# MSVC caps a single string literal at 16380 single-byte characters (C2026
# "string too big, trailing characters truncated") -- about half that for a
# literal containing non-ASCII source characters, which this one does (real
# CJK/accented family names from conf.d's alias rules) -- and the flattened
# config is well over either bound. Splitting into several literals well
# under the smaller limit, stored as separate array entries (never
# concatenated by the compiler into one literal), sidesteps it regardless of
# total size; the pieces are joined back into one buffer at runtime instead
# (see LWEDelegate.cpp).
MAX_CHUNK_BYTES = 4000

