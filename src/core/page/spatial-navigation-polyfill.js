"    return (element.tagName === 'A' && element.getAttribute('href') === null && element.getAttribute('tabIndex') === null);\n"
"  }\n"
"\n"
"  /**\n"
"   * Decide whether an element is actually disabled or not.\n"
"   *\n"
"   * @function isActuallyDisabled\n"
